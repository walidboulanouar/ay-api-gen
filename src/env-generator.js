/**
 * .env.example generator.
 * Creates a .env.example file with the right variables based on detected security schemes.
 */

/**
 * Generate .env.example content based on security schemes and base URL.
 * @param {object} securitySchemes
 * @param {string} baseUrl
 * @param {object} info - API info from spec
 * @returns {string}
 */
export function generateEnvExample(securitySchemes, baseUrl, info = {}) {
  const lines = [];
  const schemes = Object.values(securitySchemes || {});

  lines.push("# " + (info.title || "API") + " — Environment Configuration");
  lines.push("# Generated by ay-api-gen");
  lines.push("");

  lines.push("# Base URL (override if using a different environment)");
  lines.push("# API_BASE_URL=" + baseUrl);
  lines.push("");

  if (schemes.length === 0) {
    lines.push("# No security schemes detected. Generic auth:");
    lines.push("# API_KEY=your-api-key-here");
    lines.push("# API_TOKEN=your-token-here");
    lines.push("");
    lines.push("# Custom header auth:");
    lines.push("# API_HEADER_NAME=X-Custom-Header");
    lines.push("# API_HEADER_VALUE=your-value");
    return lines.join("\n") + "\n";
  }

  const hasBearer = schemes.some(s => s.type === "http" && s.scheme === "bearer");
  const hasBasic = schemes.some(s => s.type === "http" && s.scheme === "basic");
  const hasApiKeyHeader = schemes.filter(s => s.type === "apiKey" && s.in === "header");
  const hasApiKeyQuery = schemes.filter(s => s.type === "apiKey" && s.in === "query");
  const hasOAuth2 = schemes.some(s => s.type === "oauth2");

  if (hasBearer) {
    const bearerScheme = schemes.find(s => s.type === "http" && s.scheme === "bearer");
    lines.push("# Bearer Token Authentication" + (bearerScheme.bearerFormat ? " (" + bearerScheme.bearerFormat + ")" : ""));
    lines.push("API_BEARER_TOKEN=your-bearer-token-here");
    lines.push("");
  }

  if (hasBasic) {
    lines.push("# Basic Authentication");
    lines.push("API_USERNAME=your-username");
    lines.push("API_PASSWORD=your-password");
    lines.push("");
  }

  for (const s of hasApiKeyHeader) {
    lines.push("# API Key — sent as header: " + s.paramName);
    lines.push("API_KEY=your-api-key-here");
    lines.push("");
  }

  for (const s of hasApiKeyQuery) {
    lines.push("# API Key — sent as query param: " + s.paramName);
    lines.push("API_KEY=your-api-key-here");
    lines.push("");
  }

  if (hasOAuth2) {
    const oauthScheme = schemes.find(s => s.type === "oauth2");
    const flowTypes = Object.keys(oauthScheme.flows || {});
    const flow = Object.values(oauthScheme.flows || {})[0];

    lines.push("# OAuth2 Authentication (flows: " + flowTypes.join(", ") + ")");
    lines.push("# Option 1: Pre-obtained access token");
    lines.push("OAUTH_ACCESS_TOKEN=your-access-token-here");
    lines.push("");
    lines.push("# Option 2: Client credentials (auto-refresh)");
    lines.push("# OAUTH_CLIENT_ID=your-client-id");
    lines.push("# OAUTH_CLIENT_SECRET=your-client-secret");
    if (flow?.tokenUrl) {
      lines.push("# OAUTH_TOKEN_URL=" + flow.tokenUrl);
    }
    if (flow?.scopes && Object.keys(flow.scopes).length > 0) {
      lines.push("#");
      lines.push("# Available scopes:");
      for (const [scope, desc] of Object.entries(flow.scopes)) {
        lines.push("#   " + scope + (desc ? " — " + desc : ""));
      }
    }
    lines.push("");
  }

  return lines.join("\n") + "\n";
}
