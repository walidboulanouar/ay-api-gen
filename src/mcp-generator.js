/**
 * MCP Server Generator.
 * Takes parsed endpoints and generates a standalone MCP server file
 * that can be registered in Claude Code's settings.json.
 */

import { generateAuthCode } from "./auth-codegen.js";

/**
 * Build MCP tool input schema from endpoint parameters + request body.
 */
function buildToolInputSchema(endpoint) {
  const properties = {};
  const required = [];

  // Path/query/header parameters
  for (const param of endpoint.parameters) {
    if (param.in === "header") continue; // headers handled via auth
    properties[param.name] = {
      type: param.schema?.type || "string",
      description: param.description || `${param.in} parameter: ${param.name}`,
    };
    if (param.schema?.enum) {
      properties[param.name].enum = param.schema.enum;
    }
    if (param.required) {
      required.push(param.name);
    }
  }

  // Request body properties
  if (endpoint.requestBody?.schema?.properties) {
    for (const [key, val] of Object.entries(endpoint.requestBody.schema.properties)) {
      properties[key] = {
        type: val.type || "string",
        description: val.description || key,
      };
      if (val.enum) properties[key].enum = val.enum;
    }
    if (endpoint.requestBody.schema.required) {
      required.push(...endpoint.requestBody.schema.required);
    }
  }

  return { properties, required };
}

/**
 * Generate the MCP server source code as a string.
 * @param {object} parsed - Output from extractEndpoints()
 * @param {object} options - { name, outputDir }
 * @returns {string} - Complete MCP server JS source
 */
export function generateMCPServer(parsed, options = {}) {
  const { baseUrl, info, endpoints, securitySchemes = {} } = parsed;
  const apiName = options.name || info.title?.replace(/[^a-zA-Z0-9]/g, "-").toLowerCase() || "api";

  const toolDefs = endpoints.map(ep => {
    const { properties, required } = buildToolInputSchema(ep);
    return {
      name: ep.toolName,
      description: ep.summary,
      inputSchema: {
        type: "object",
        properties,
        required: required.length > 0 ? required : undefined,
      },
      _endpoint: {
        method: ep.method,
        path: ep.path,
        parameters: ep.parameters,
        hasBody: !!ep.requestBody,
      },
    };
  });

  const src = `#!/usr/bin/env node
/**
 * MCP Server: ${info.title || apiName}
 * ${info.description || "Auto-generated from OpenAPI spec"}
 *
 * Generated by ay-api-gen
 */

import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";
import { readFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

// ── Config ──
const BASE_URL = process.env.API_BASE_URL || ${JSON.stringify(baseUrl)};

// Load .env if present
function loadEnv() {
  const envPaths = [
    resolve(__dirname, ".env"),
    resolve(process.cwd(), ".env"),
  ];
  for (const p of envPaths) {
    if (existsSync(p)) {
      const lines = readFileSync(p, "utf-8").split("\\n");
      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith("#")) continue;
        const eqIdx = trimmed.indexOf("=");
        if (eqIdx === -1) continue;
        const key = trimmed.slice(0, eqIdx).trim();
        let val = trimmed.slice(eqIdx + 1).trim();
        if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
          val = val.slice(1, -1);
        }
        if (!process.env[key]) process.env[key] = val;
      }
      break;
    }
  }
}
loadEnv();

${generateAuthCode(securitySchemes)}

// ── URL builder ──
function buildUrl(pathTemplate, params) {
  let url = pathTemplate;
  const queryParts = [];

  // Add auth query params (e.g. apiKey-in-query)
  const authQuery = getAuthQueryParams();
  for (const [key, value] of Object.entries(authQuery)) {
    queryParts.push(\`\${encodeURIComponent(key)}=\${encodeURIComponent(value)}\`);
  }

  for (const [key, value] of Object.entries(params)) {
    if (value === undefined || value === null) continue;
    if (url.includes(\`{\${key}}\`)) {
      url = url.replace(\`{\${key}}\`, encodeURIComponent(value));
    } else {
      queryParts.push(\`\${encodeURIComponent(key)}=\${encodeURIComponent(value)}\`);
    }
  }

  const fullUrl = BASE_URL.replace(/\\/$/, "") + url;
  return queryParts.length > 0 ? \`\${fullUrl}?\${queryParts.join("&")}\` : fullUrl;
}

// ── API caller ──
async function callApi(method, pathTemplate, params, bodyParams) {
  const url = buildUrl(pathTemplate, params);
  const headers = getAuthHeaders();

  const fetchOpts = { method, headers };
  if (bodyParams && Object.keys(bodyParams).length > 0 && method !== "GET" && method !== "HEAD") {
    fetchOpts.body = JSON.stringify(bodyParams);
  }

  try {
    const res = await fetch(url, fetchOpts);
    const text = await res.text();
    let data;
    try { data = JSON.parse(text); } catch { data = text; }

    if (!res.ok) {
      return { error: true, status: res.status, statusText: res.statusText, body: data };
    }
    return data;
  } catch (err) {
    return { error: true, message: err.message };
  }
}

// ── Server setup ──
const server = new McpServer({
  name: ${JSON.stringify(apiName)},
  version: ${JSON.stringify(info.version || "1.0.0")},
});

// ── Tool definitions ──
${toolDefs.map(tool => {
    const ep = tool._endpoint;
    const pathParams = ep.parameters.filter(p => p.in === "path").map(p => p.name);
    const queryParams = ep.parameters.filter(p => p.in === "query").map(p => p.name);
    const bodyKeys = tool.inputSchema.properties
      ? Object.keys(tool.inputSchema.properties).filter(k => !pathParams.includes(k) && !queryParams.includes(k))
      : [];

    const schemaEntries = Object.entries(tool.inputSchema.properties || {});

    // Generate Zod schema entries
    function zodForType(v, isRequired) {
      let zod;
      switch (v.type) {
        case "integer": case "number": zod = "z.coerce.number()"; break;
        case "boolean": zod = "z.coerce.boolean()"; break;
        case "array": zod = "z.array(z.any())"; break;
        default: zod = "z.string()"; break;
      }
      if (v.enum) {
        zod = `z.enum(${JSON.stringify(v.enum)})`;
      }
      if (v.description) {
        zod += `.describe(${JSON.stringify(v.description)})`;
      }
      if (!isRequired) {
        zod += `.optional()`;
      }
      return zod;
    }

    return `
server.tool(
  ${JSON.stringify(tool.name)},
  ${JSON.stringify(tool.description)},
  {
${schemaEntries.map(([k, v]) => {
    const isRequired = tool.inputSchema.required?.includes(k);
    return `    ${JSON.stringify(k)}: ${zodForType(v, isRequired)}`;
  }).join(",\n")}
  },
  async (params) => {
    const pathQueryParams = {};
    const bodyParams = {};

    for (const [k, v] of Object.entries(params)) {
${pathParams.length > 0 ? `      if (${JSON.stringify(pathParams)}.includes(k)) { pathQueryParams[k] = v; continue; }` : ""}
${queryParams.length > 0 ? `      if (${JSON.stringify(queryParams)}.includes(k)) { pathQueryParams[k] = v; continue; }` : ""}
      ${ep.hasBody ? "bodyParams[k] = v;" : "pathQueryParams[k] = v;"}
    }

    const result = await callApi(${JSON.stringify(ep.method)}, ${JSON.stringify(ep.path)}, pathQueryParams, bodyParams);
    return { content: [{ type: "text", text: JSON.stringify(result, null, 2) }] };
  }
);`;
  }).join("\n")}

// ── Start server ──
const transport = new StdioServerTransport();
await server.connect(transport);
`;

  return src;
}
