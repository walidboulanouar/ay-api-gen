/**
 * CLI Generator.
 * Takes parsed endpoints and generates a standalone CLI file.
 * Each endpoint becomes a command: ay-api <resource> <action> [--param value]
 * Zero external deps — uses Node.js built-in arg parsing.
 */

import { generateAuthCode, generateEnvDocs } from "./auth-codegen.js";

/**
 * Generate the CLI source code as a string.
 * @param {object} parsed - Output from extractEndpoints()
 * @param {object} options - { name }
 * @returns {string}
 */
export function generateCLI(parsed, options = {}) {
  const { baseUrl, info, endpoints, securitySchemes = {} } = parsed;
  const apiName = options.name || info.title?.replace(/[^a-zA-Z0-9]/g, "-").toLowerCase() || "api";
  const binName = `ay-${apiName}`;

  // Group endpoints by resource
  const groups = {};
  for (const ep of endpoints) {
    const { resource, action } = ep.cliCommand;
    if (!groups[resource]) groups[resource] = [];
    groups[resource].push({ ...ep, action });
  }

  const src = `#!/usr/bin/env node
/**
 * CLI: ${info.title || apiName}
 * ${info.description || "Auto-generated from OpenAPI spec"}
 *
 * Usage:
 *   ${binName} <resource> <action> [--param value ...]
 *   ${binName} --help
 *
 * Generated by ay-api-gen
 */

import { readFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

// ── .env loader ──
function loadEnv() {
  const envPaths = [resolve(__dirname, ".env"), resolve(process.cwd(), ".env")];
  for (const p of envPaths) {
    if (existsSync(p)) {
      const lines = readFileSync(p, "utf-8").split("\\n");
      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith("#")) continue;
        const eqIdx = trimmed.indexOf("=");
        if (eqIdx === -1) continue;
        const key = trimmed.slice(0, eqIdx).trim();
        let val = trimmed.slice(eqIdx + 1).trim();
        if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
          val = val.slice(1, -1);
        }
        if (!process.env[key]) process.env[key] = val;
      }
      break;
    }
  }
}
loadEnv();

// ── Config ──
const BASE_URL = process.env.API_BASE_URL || ${JSON.stringify(baseUrl)};

${generateAuthCode(securitySchemes)}

function buildUrl(pathTemplate, params) {
  let url = pathTemplate;
  const queryParts = [];

  // Add auth query params (e.g. apiKey-in-query)
  const authQuery = getAuthQueryParams();
  for (const [key, value] of Object.entries(authQuery)) {
    queryParts.push(\`\${encodeURIComponent(key)}=\${encodeURIComponent(value)}\`);
  }

  for (const [key, value] of Object.entries(params)) {
    if (value === undefined || value === null) continue;
    if (url.includes(\`{\${key}}\`)) {
      url = url.replace(\`{\${key}}\`, encodeURIComponent(value));
    } else {
      queryParts.push(\`\${encodeURIComponent(key)}=\${encodeURIComponent(value)}\`);
    }
  }
  const fullUrl = BASE_URL.replace(/\\/$/, "") + url;
  return queryParts.length > 0 ? \`\${fullUrl}?\${queryParts.join("&")}\` : fullUrl;
}

async function callApi(method, pathTemplate, params, bodyParams) {
  const url = buildUrl(pathTemplate, params);
  const headers = getAuthHeaders();
  const fetchOpts = { method, headers };
  if (bodyParams && Object.keys(bodyParams).length > 0 && method !== "GET" && method !== "HEAD") {
    fetchOpts.body = JSON.stringify(bodyParams);
  }
  const res = await fetch(url, fetchOpts);
  const text = await res.text();
  let data;
  try { data = JSON.parse(text); } catch { data = text; }
  if (!res.ok) {
    console.error(\`Error \${res.status}: \${res.statusText}\`);
    console.error(typeof data === "string" ? data : JSON.stringify(data, null, 2));
    process.exit(1);
  }
  return data;
}

// ── Arg parser ──
function parseArgs(argv) {
  const args = {};
  const positional = [];
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith("--")) {
      const key = argv[i].slice(2);
      const next = argv[i + 1];
      if (next && !next.startsWith("--")) {
        args[key] = next;
        i++;
      } else {
        args[key] = true;
      }
    } else {
      positional.push(argv[i]);
    }
  }
  return { args, positional };
}

// ── Command registry ──
const commands = {};

function register(resource, action, config) {
  if (!commands[resource]) commands[resource] = {};
  commands[resource][action] = config;
}

// ── Register all endpoints ──
${Object.entries(groups).map(([resource, eps]) => {
    return eps.map(ep => {
      const pathParams = ep.parameters.filter(p => p.in === "path").map(p => p.name);
      const queryParams = ep.parameters.filter(p => p.in === "query").map(p => p.name);
      const bodyProps = ep.requestBody?.schema?.properties ? Object.keys(ep.requestBody.schema.properties) : [];
      const allParams = [...new Set([...pathParams, ...queryParams, ...bodyProps])];

      return `register(${JSON.stringify(resource)}, ${JSON.stringify(ep.action)}, {
  description: ${JSON.stringify(ep.summary)},
  method: ${JSON.stringify(ep.method)},
  path: ${JSON.stringify(ep.path)},
  pathParams: ${JSON.stringify(pathParams)},
  queryParams: ${JSON.stringify(queryParams)},
  bodyParams: ${JSON.stringify(bodyProps)},
  params: ${JSON.stringify(allParams)},
});`;
    }).join("\n\n");
  }).join("\n\n")}

// ── Help ──
function printHelp() {
  console.log(\`
${binName} - CLI for ${info.title || apiName}

Usage:
  ${binName} <resource> <action> [--param value ...]
  ${binName} --help

Resources:
\${Object.entries(commands).map(([res, actions]) =>
  \`  \${res}\\n\${Object.entries(actions).map(([act, cfg]) =>
    \`    \${act.padEnd(12)} \${cfg.description}\`
  ).join("\\n")}\`
).join("\\n\\n")}

Environment variables:
${generateEnvDocs(securitySchemes)}
\`);
}

// ── Main ──
const { args, positional } = parseArgs(process.argv.slice(2));

if (args.help || positional.length === 0) {
  printHelp();
  process.exit(0);
}

const [resource, action] = positional;
const cmd = commands[resource]?.[action];

if (!cmd) {
  console.error(\`Unknown command: \${resource} \${action || ""}\`);
  console.error(\`Run "${binName} --help" for available commands.\`);
  process.exit(1);
}

// Split args into path/query vs body
const pathQueryParams = {};
const bodyParams = {};

for (const [k, v] of Object.entries(args)) {
  if (k === "help") continue;
  if (cmd.pathParams.includes(k) || cmd.queryParams.includes(k)) {
    pathQueryParams[k] = v;
  } else {
    bodyParams[k] = v;
  }
}

const result = await callApi(cmd.method, cmd.path, pathQueryParams, bodyParams);
console.log(typeof result === "string" ? result : JSON.stringify(result, null, 2));
`;

  return src;
}
